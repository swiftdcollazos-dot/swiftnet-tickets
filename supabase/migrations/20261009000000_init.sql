-- Swiftnet service tickets: database schema.
-- Run this in the Supabase dashboard: SQL Editor > New query > paste > Run.
-- It is safe to run again: anything already created is left as it is.

-- Business settings (a single row).
create table if not exists public.settings (
  id               int primary key default 1 check (id = 1),
  company_name     text not null default 'Swiftnet',
  company_phone    text not null default '',
  company_email    text not null default '',
  company_address  text not null default '',
  currency         text not null default 'USD',
  hourly_rate_cents int not null default 9000,      -- $90.00 / hour
  tax_rate_pct     numeric(5,2) not null default 0, -- e.g. 5.00 for 5%
  tax_labor        boolean not null default true,   -- false = tax materials only
  rounding_minutes int not null default 60,         -- billable time rounds up to this (60 = whole hours)
  minimum_minutes  int not null default 60,         -- minimum billable time per ticket
  terms            text not null default 'TERMS - NET CASH. NO GOODS HELD OVER 30 DAYS.',
  disclaimer       text not null default 'We will not be responsible for loss or damage caused by fire, theft, testing, or any other causes beyond our control.'
);
insert into public.settings (id) values (1) on conflict (id) do nothing;

-- One row per person who logs in (David, Daniel, ...).
create table if not exists public.profiles (
  id        uuid primary key references auth.users (id) on delete cascade,
  full_name text not null
);

create table if not exists public.clients (
  id         uuid primary key default gen_random_uuid(),
  name       text not null,
  phone      text not null default '',
  email      text not null default '',
  address    text not null default '',
  created_at timestamptz not null default now()
);
-- Hourly clients pay per visit; contract clients are on a service agreement.
alter table public.clients add column if not exists client_type text not null default 'hourly'
  check (client_type in ('hourly', 'contract'));
alter table public.clients add column if not exists monthly_fee_cents int not null default 0;

do $$ begin
  create type public.ticket_kind as enum ('service', 'install', 'will_call', 'deliver');
exception when duplicate_object then null; end $$;
do $$ begin
  create type public.ticket_status as enum ('open', 'completed', 'paid');
exception when duplicate_object then null; end $$;

create table if not exists public.tickets (
  id                uuid primary key default gen_random_uuid(),
  number            int generated by default as identity (start with 1001) unique,
  client_id         uuid not null references public.clients (id),
  technician_id     uuid references public.profiles (id),
  ticket_date       date not null default current_date,
  kind              public.ticket_kind not null default 'service',
  is_estimate       boolean not null default false,
  status            public.ticket_status not null default 'open',
  item_to_service   text not null default '',
  make              text not null default '',
  model             text not null default '',
  serial            text not null default '',
  service_request   text not null default '',  -- "Nature of service request"
  labor_performed   text not null default '',
  date_wanted       date,
  deposit_cents     int not null default 0,
  -- Billing rules are copied onto each ticket so changing settings later
  -- never changes an old ticket's total.
  hourly_rate_cents int not null,
  tax_rate_pct      numeric(5,2) not null,
  tax_labor         boolean not null,
  rounding_minutes  int not null,
  minimum_minutes   int not null,
  signature         text,   -- PNG data URL of the client's signature
  signed_name       text,
  signed_at         timestamptz,
  created_at        timestamptz not null default now()
);

create table if not exists public.time_entries (
  id            uuid primary key default gen_random_uuid(),
  ticket_id     uuid not null references public.tickets (id) on delete cascade,
  technician_id uuid references public.profiles (id),
  started_at    timestamptz not null,
  ended_at      timestamptz,   -- null while the timer is running
  check (ended_at is null or ended_at >= started_at)
);

create table if not exists public.ticket_parts (
  id               uuid primary key default gen_random_uuid(),
  ticket_id        uuid not null references public.tickets (id) on delete cascade,
  qty              numeric(10,2) not null default 1,
  part_number      text not null default '',
  description      text not null,
  unit_price_cents int not null default 0
);

alter table public.tickets add column if not exists machine_name text not null default '';
-- Special projects: jobs like service tickets, listed on their own tab.
alter table public.tickets add column if not exists is_project boolean not null default false;
-- "Contacted by" on service tickets, calls and projects.
alter table public.tickets add column if not exists contacted_by text not null default '';
-- Who created the job; technician_id is who it is assigned to and can change.
alter table public.tickets add column if not exists created_by uuid references public.profiles (id);
update public.tickets set created_by = technician_id where created_by is null;
-- Service type is free text from the app's Type list (was a fixed 4-value list).
alter table public.tickets alter column kind drop default;
alter table public.tickets alter column kind type text using kind::text;
alter table public.tickets alter column kind set default '';

create index if not exists tickets_client_id_idx on public.tickets (client_id);
create index if not exists time_entries_ticket_id_idx on public.time_entries (ticket_id);
create index if not exists ticket_parts_ticket_id_idx on public.ticket_parts (ticket_id);

