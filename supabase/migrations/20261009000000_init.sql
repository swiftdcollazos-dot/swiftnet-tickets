-- Expenses, with an optional photo of the receipt.
create table if not exists public.expenses (
  id             uuid primary key default gen_random_uuid(),
  spent_on       date not null default current_date,
  vendor         text not null default '',
  category       text not null default 'Other',
  description    text not null default '',
  amount_cents   integer not null default 0,
  tax_cents      integer not null default 0,
  payment_method text not null default '',
  receipt        text,
  created_by     uuid references auth.users (id) on delete set null default auth.uid(),
  created_at     timestamptz not null default now()
);
create index if not exists expenses_spent_on_idx on public.expenses (spent_on);
alter table public.expenses enable row level security;
-- Everyone can report expenses and see their own; the owner sees them all.
drop policy if exists "owner only" on public.expenses;
drop policy if exists "own or owner" on public.expenses;
create policy "own or owner" on public.expenses for all to authenticated
  using (created_by = auth.uid() or lower(auth.jwt() ->> 'email') = 'david@swiftnetit.com')
  with check (created_by = auth.uid() or lower(auth.jwt() ->> 'email') = 'david@swiftnetit.com');

-- Owner-only renewal dates: licenses, domains, SSL certificates, warranties, contracts.
create table if not exists public.renewals (
  id            uuid primary key default gen_random_uuid(),
  client_id     uuid references public.clients (id) on delete cascade,
  kind          text not null default 'Other',
  name          text not null default '',
  due_on        date not null,
  repeat_months integer not null default 12,  -- 0 = only once
  cost_cents    integer not null default 0,
  notes         text not null default '',
  created_at    timestamptz not null default now()
);
create index if not exists renewals_due_on_idx on public.renewals (due_on);
alter table public.renewals enable row level security;
drop policy if exists "owner only" on public.renewals;
create policy "owner only" on public.renewals for all to authenticated
  using (lower(auth.jwt() ->> 'email') = 'david@swiftnetit.com')
  with check (lower(auth.jwt() ->> 'email') = 'david@swiftnetit.com');

-- Items bought to resell: the customer to charge, the markup, and whether it's been charged.
alter table public.expenses add column if not exists bill_client_id uuid references public.clients (id) on delete set null;
alter table public.expenses add column if not exists markup_pct integer not null default 0;
alter table public.expenses add column if not exists charged boolean not null default false;
-- Which company vehicle a "Fuel and vehicle" expense was for.
alter table public.expenses add column if not exists vehicle text not null default '';

-- Each item on an expense's invoice, so items can be charged to different customers.
create table if not exists public.expense_items (
  id             uuid primary key default gen_random_uuid(),
  expense_id     uuid not null references public.expenses (id) on delete cascade,
  position       integer not null default 0,
  description    text not null default '',
  amount_cents   integer not null default 0,
  bill_client_id uuid references public.clients (id) on delete set null,
  markup_pct     integer not null default 0,
  charged        boolean not null default false
);
create index if not exists expense_items_expense_id_idx on public.expense_items (expense_id);
alter table public.expense_items enable row level security;
drop policy if exists "same as its expense" on public.expense_items;
create policy "same as its expense" on public.expense_items for all to authenticated
  using (exists (select 1 from public.expenses e where e.id = expense_id))
  with check (exists (select 1 from public.expenses e where e.id = expense_id));
-- Expenses already charged to a customer as a whole become one item each.
insert into public.expense_items (expense_id, description, amount_cents, bill_client_id, markup_pct, charged)
select e.id, coalesce(nullif(e.description, ''), e.vendor), e.amount_cents, e.bill_client_id, e.markup_pct, e.charged
from public.expenses e
where e.bill_client_id is not null
  and not exists (select 1 from public.expense_items i where i.expense_id = e.id);

-- Remote or on-site service, chosen next to the client signature ('' = not chosen).
alter table public.tickets add column if not exists service_location text not null default '';
-- Swiftnet IT itself: time on its jobs is tracked for the records but never billed.
alter table public.clients add column if not exists internal boolean not null default false;
-- An expense item bought for a customer's job: it shows on that job at cost plus markup.
alter table public.expense_items add column if not exists ticket_id uuid references public.tickets (id) on delete set null;
create index if not exists expense_items_ticket_id_idx on public.expense_items (ticket_id);
-- Everyone who can open a job sees the items bought for it, so its total is the same for all.
drop policy if exists "on a job" on public.expense_items;
create policy "on a job" on public.expense_items for select to authenticated using (ticket_id is not null);
-- A standing service call that repeats every week or month: it stays open, and each visit's time counts when it was worked.
alter table public.tickets add column if not exists repeats text not null default '';

