-- Swiftnet service tickets: database schema.
-- Run this once in the Supabase dashboard: SQL Editor > New query > paste > Run.

-- Business settings (a single row).
create table public.settings (
  id               int primary key default 1 check (id = 1),
  company_name     text not null default 'Swiftnet',
  company_phone    text not null default '',
  company_email    text not null default '',
  company_address  text not null default '',
  currency         text not null default 'USD',
  hourly_rate_cents int not null default 9000,      -- $90.00 / hour
  tax_rate_pct     numeric(5,2) not null default 0, -- e.g. 5.00 for 5%
  tax_labor        boolean not null default true,   -- false = tax materials only
  rounding_minutes int not null default 15,         -- billable time rounds up to this
  minimum_minutes  int not null default 0,          -- minimum billable time per ticket
  terms            text not null default 'TERMS - NET CASH. NO GOODS HELD OVER 30 DAYS.',
  disclaimer       text not null default 'We will not be responsible for loss or damage caused by fire, theft, testing, or any other causes beyond our control.'
);
insert into public.settings (id) values (1);

-- One row per person who logs in (David, Daniel, ...).
create table public.profiles (
  id        uuid primary key references auth.users (id) on delete cascade,
  full_name text not null
);

create table public.clients (
  id         uuid primary key default gen_random_uuid(),
  name       text not null,
  phone      text not null default '',
  email      text not null default '',
  address    text not null default '',
  created_at timestamptz not null default now()
);

create type public.ticket_kind   as enum ('service', 'install', 'will_call', 'deliver');
create type public.ticket_status as enum ('open', 'completed', 'paid');

create table public.tickets (
  id                uuid primary key default gen_random_uuid(),
  number            int generated by default as identity (start with 1001) unique,
  client_id         uuid not null references public.clients (id),
  technician_id     uuid references public.profiles (id),
  ticket_date       date not null default current_date,
  kind              public.ticket_kind not null default 'service',
  is_estimate       boolean not null default false,
  status            public.ticket_status not null default 'open',
  item_to_service   text not null default '',
  make              text not null default '',
  model             text not null default '',
  serial            text not null default '',
  service_request   text not null default '',  -- "Nature of service request"
  labor_performed   text not null default '',
  date_wanted       date,
  deposit_cents     int not null default 0,
  -- Billing rules are copied onto each ticket so changing settings later
  -- never changes an old ticket's total.
  hourly_rate_cents int not null,
  tax_rate_pct      numeric(5,2) not null,
  tax_labor         boolean not null,
  rounding_minutes  int not null,
  minimum_minutes   int not null,
  signature         text,   -- PNG data URL of the client's signature
  signed_name       text,
  signed_at         timestamptz,
  created_at        timestamptz not null default now()
);

create table public.time_entries (
  id            uuid primary key default gen_random_uuid(),
  ticket_id     uuid not null references public.tickets (id) on delete cascade,
  technician_id uuid references public.profiles (id),
  started_at    timestamptz not null,
  ended_at      timestamptz,   -- null while the timer is running
  check (ended_at is null or ended_at >= started_at)
);

create table public.ticket_parts (
  id               uuid primary key default gen_random_uuid(),
  ticket_id        uuid not null references public.tickets (id) on delete cascade,
  qty              numeric(10,2) not null default 1,
  part_number      text not null default '',
  description      text not null,
  unit_price_cents int not null default 0
);

create index on public.tickets (client_id);
create index on public.time_entries (ticket_id);
create index on public.ticket_parts (ticket_id);

-- Only logged-in staff can read or change anything. There is no public sign-up:
-- users are added by hand in Supabase (Authentication > Users).
do $$
declare t text;
begin
  foreach t in array array['settings','profiles','clients','tickets','time_entries','ticket_parts'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('create policy "staff full access" on public.%I for all to authenticated using (true) with check (true)', t);
  end loop;
end $$;

-- Create a profile automatically when a user is added in Supabase.
-- Put the person's name in "User Metadata" as {"full_name": "David Collazos"}.
create function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', new.email));
  return new;
end $$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();
